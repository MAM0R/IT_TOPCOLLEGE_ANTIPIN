list5 = [12,3122,32,322,6934]

#Добавление
list5.append(10) #добавляет в конец списка: 10
print(list5)

#Удаление элемента по значению (если несколько 12 удаляет лишь самый первый)
list5.remove(12) #удаляет 12 с таблицы

#Удаление элемента по индексу
element = list5.pop(3) #element = элемент который мы удалили по индексу
print("удалён", element)
print(list5)

#Добавление списка
new_list = ["Йоу", "Печенье"]
list5.extend(new_list) #Расширяем list5 и в него добавляются элементы с new_list
print(list5)

#Добавление по индексу
list5.insert(0, "Программное обеспечение") #Программное обеспечение встанет в начале списка
print(list5)

#Поиск по индексу
index = list5.index("Программное обеспечение")
print("Элемент на позиции", index)

#Очистка списка
list5.clear() #делает список пустым
print(list5)

